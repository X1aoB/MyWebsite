// Regenerates src/styles/ambient-tiles.css: the inline SVG tiles of the ambient layer
// (snow for 尘尘的白, wheat grains and leaves for 苹果与狼). Run: node scripts/generate-ambient-tiles.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/styles/ambient-tiles.css");
const uri = (svg) => `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/[<>#%{}\n]/g, (c) => encodeURIComponent(c))}")`;
const tile = (size, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}">${body}</svg>`;

const flakes = (size, stroke, list) => tile(size, `<g fill="white" stroke="rgb(110,172,214)" stroke-opacity=".5" stroke-width="${stroke}">${
  list.map(([x, y, r]) => `<circle cx="${x}" cy="${y}" r="${r}"/>`).join("")}</g>`);
const grains = (size, list) => tile(size, `<g fill="#d6a03f" fill-opacity=".6">${
  list.map(([x, y, a]) => `<ellipse cx="${x}" cy="${y}" rx="2.8" ry="1.25" transform="rotate(${a} ${x} ${y})"/>`).join("")}</g>`);
const leaves = (size, list) => tile(size, `<g fill="#c47533" fill-opacity=".42">${
  list.map(([x, y, a, s]) => `<path transform="translate(${x} ${y}) rotate(${a}) scale(${s})" d="M0 0c4-5 11-5 15 0-4 5-11 5-15 0Z"/>`).join("")}</g>`);

// Tile sizes must match the travel distances in motion.css so the loops are seamless.
const tiles = {
  "--ambient-ice-far": flakes(300, 0.6, [[23, 41, 1.6], [88, 12, 1.1], [141, 77, 1.9], [212, 33, 1.3], [268, 96, 1.7], [52, 158, 1.2], [176, 190, 1.5], [245, 232, 1.1], [110, 262, 1.8], [19, 247, 1.3]]),
  "--ambient-ice-near": flakes(560, 0.8, [[60, 90, 3.2], [250, 40, 2.6], [410, 170, 3.6], [150, 330, 2.8], [470, 420, 3.1], [320, 500, 2.7]]),
  "--ambient-holo-far": grains(320, [[31, 52, 35], [104, 18, -20], [168, 96, 60], [242, 44, 10], [290, 140, -45], [62, 186, 25], [190, 222, -10], [130, 290, 50], [270, 270, 15]]),
  "--ambient-holo-near": leaves(600, [[80, 120, 25, 1.1], [330, 60, -30, 0.9], [470, 260, 70, 1.2], [180, 420, -10, 1], [420, 520, 40, 0.85]])
};

const css = `/* Generated by scripts/generate-ambient-tiles.mjs. Do not edit by hand. */\n:root {\n${
  Object.entries(tiles).map(([name, svg]) => `  ${name}: ${uri(svg)};`).join("\n")}\n}\n`;
fs.writeFileSync(out, css);
console.log(`wrote ${path.relative(process.cwd(), out)} (${css.length} bytes)`);
