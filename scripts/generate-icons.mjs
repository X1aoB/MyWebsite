// Regenerates src/lib/icons.ts from pinned lucide-static and simple-icons packages.
//
// The packages are not project dependencies. Install them without touching package.json:
//   npm install --no-save lucide-static@1.57.0 simple-icons@16.35.0
//   node scripts/generate-icons.mjs
// Add a name to `lucide` or `brands` below, then regenerate. The output only holds
// static SVG geometry; src/lib/icons.test.ts guards that.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulesRoot = path.resolve(process.argv[2] ?? path.join(repoRoot, "node_modules"));
const out = path.join(repoRoot, "src/lib/icons.ts");

const lucide = [
  "house", "notebook-pen", "messages-square", "wrench", "camera", "clock", "user-round", "link",
  "chevron-down", "arrow-right", "arrow-left", "arrow-up", "arrow-up-right", "x", "search",
  "sliders-horizontal", "radar", "package", "braces", "snowflake", "mail", "sparkles",
  "message-square-text", "users-round", "maximize-2", "images", "rss", "info", "align-left",
  "refresh-cw", "download", "arrow-down", "play", "pause", "map", "bell-ring", "smartphone", "book-heart"
];
const brands = { bilibili: "bilibili", github: "github", steam: "steam" };

const lucideRoot = path.join(modulesRoot, "lucide-static");
const brandRoot = path.join(modulesRoot, "simple-icons");
const lucidePkg = JSON.parse(await fs.readFile(path.join(lucideRoot, "package.json"), "utf8"));
const brandPkg = JSON.parse(await fs.readFile(path.join(brandRoot, "package.json"), "utf8"));
const license = (await fs.readFile(path.join(lucideRoot, "LICENSE"), "utf8")).trim();

const entries = [];
for (const name of lucide) {
  const svg = await fs.readFile(path.join(lucideRoot, "icons", `${name}.svg`), "utf8");
  const body = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s*\n\s*/g, "").replace(/\s{2,}/g, " ").replace(/\s*\/>/g, "/>").trim();
  if (!body) throw new Error(`empty lucide icon ${name}`);
  entries.push([name, "stroke", body]);
}
for (const [name, file] of Object.entries(brands)) {
  const svg = await fs.readFile(path.join(brandRoot, "icons", `${file}.svg`), "utf8");
  const d = svg.match(/<path d="([^"]+)"/)?.[1];
  if (!d) throw new Error(`missing brand path ${file}`);
  entries.push([name, "fill", `<path d="${d}"/>`]);
}

const comment = license.split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n");
const source = `/*
 * Generated by scripts/generate-icons.mjs. Do not edit by hand.
 *
 * Line icons: lucide-static ${lucidePkg.version} (ISC). Brand marks: simple-icons ${brandPkg.version}
 * (CC0 1.0); the brands themselves remain trademarks of their owners.
 *
${comment}
 */

export type IconKind = "stroke" | "fill";

export const icons = {
${entries.map(([name, kind, body]) => `  ${JSON.stringify(name)}: { kind: "${kind}", body: ${JSON.stringify(body)} }`).join(",\n")}
} as const satisfies Record<string, { kind: IconKind; body: string }>;

export type IconName = keyof typeof icons;

export const isIconName = (value: string): value is IconName => Object.hasOwn(icons, value);
`;
await fs.writeFile(out, source);
console.log(`wrote ${entries.length} icons to ${path.relative(repoRoot, out)}`);
